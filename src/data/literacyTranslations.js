export function getLocalizedTopic(topic, language) {
  if (!topic) return topic;
  if (language !== "hi") return topic;

  const hindiData = HINDI_TOPIC_TRANSLATIONS[topic.id];
  if (!hindiData) return topic;

  return {
    ...topic,
    title: hindiData.title || topic.title,
    tagline: hindiData.tagline || topic.tagline,
    badge: hindiData.badge || topic.badge,
    readTime: hindiData.readTime || topic.readTime,
    explanation: hindiData.explanation || topic.explanation,
    realLifeExample: hindiData.realLifeExample || topic.realLifeExample,
    dos: hindiData.dos || topic.dos,
    donts: hindiData.donts || topic.donts,
    safetyTip: hindiData.safetyTip || topic.safetyTip,
    quiz: topic.quiz.map((q, idx) => {
      const hq = hindiData.quiz?.[idx];
      if (!hq) return q;
      return {
        ...q,
        question: hq.question || q.question,
        options: hq.options || q.options,
        explanation: hq.explanation || q.explanation,
      };
    }),
  };
}
